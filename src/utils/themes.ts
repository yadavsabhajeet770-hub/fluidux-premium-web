export function applyTheme(key: string): ThemeDef {
  const t = THEMES.find((x) => x.k === key) || THEMES[0];
  if (typeof document !== 'undefined') {
    const r = document.documentElement.style;
    r.setProperty('--c1', t.c1);
    r.setProperty('--c2', t.c2);
    r.setProperty('--c3', t.c3);
    r.setProperty('--c4', t.c4);
    r.setProperty('--accent', t.accent);
    r.setProperty('--accent-2', t.accent2);
    r.setProperty('--accent-soft', t.soft);
    r.setProperty('--accent-deep', t.deep);
    r.setProperty('--bg-radial', t.bg);
    r.setProperty('--bg-base', t.base);
    r.setProperty('--dark-bg-radial', t.darkBg || '#111827');
    r.setProperty('--dark-bg-base', t.darkBase || '#030712');
    r.setProperty(
      '--hero-grad',
      t.heroGrad || `linear-gradient(135deg, ${t.deep} 0%, ${t.accent2} 50%, ${t.accent} 100%)`
    );
    r.setProperty(
      '--hero-shadow',
      t.heroShadow || `0 20px 48px -12px ${t.accent}88, inset 0 1px 0 rgba(255, 255, 255, 0.3)`
    );
    r.setProperty('--grad-deep', `linear-gradient(160deg, ${t.c3} 0%, ${t.c4} 100%)`);
    r.setProperty(
      '--grad-mint',
      `linear-gradient(160deg, ${t.c1} 0%, ${t.c2} 45%, ${t.c3} 100%)`
    );

    document.documentElement.setAttribute('data-accent', t.k);
    if (document.body) {
      document.body.setAttribute('data-accent', t.k);
    }
  }
  return t;
}
